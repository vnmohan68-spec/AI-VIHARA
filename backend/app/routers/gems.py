@router.get("")
async def list_gems(
    state:            Optional[str] = Query(None, description="State name e.g. 'Andhra Pradesh'"),
    region:           Optional[str] = Query(None, description="District/region e.g. 'Kadapa District'"),
    gem_type:         Optional[str] = Query(None, alias="type"),
    search:           Optional[str] = Query(None),
    min_hidden_score: int           = Query(70, ge=0, le=100),
    limit:            int           = Query(50, le=100),
    offset:           int           = Query(0),
    db: AsyncSession               = Depends(get_db),
):
    """
    List hidden gems with strict state + district filtering.
    When state='Andhra Pradesh' AND region='Kadapa District',
    ONLY Kadapa gems are returned — not all Andhra gems.
    """
    try:
        query = select(HiddenGem).where(HiddenGem.hidden_score >= min_hidden_score)
        if state and state not in ("All States", ""):
            query = query.where(HiddenGem.state.ilike(f"%{state}%"))
        if region and region not in ("All Districts", ""):
            # Strict: region must match — not just contain
            query = query.where(HiddenGem.region.ilike(f"%{region}%"))
        if gem_type and gem_type != "All":
            query = query.where(HiddenGem.type.ilike(f"%{gem_type}%"))
        if search:
            s = f"%{search}%"
            query = query.where(or_(
                HiddenGem.name.ilike(s),
                HiddenGem.state.ilike(s),
                HiddenGem.region.ilike(s),
                HiddenGem.story.ilike(s),
            ))
        query  = query.order_by(HiddenGem.hidden_score.desc()).offset(offset).limit(limit)
        result = await db.execute(query)
        gems   = result.scalars().all()
        if gems:
            return [_gem_to_dict(g) for g in gems]
    except Exception as exc:
        logger.warning("DB unavailable (%s) — filtering seed data", exc)

    # ── Seed fallback — strict filtering ─────────────────────────
    return _filter_seeds(
        seeds     = SEED_GEMS,
        state     = state,
        region    = region,
        gem_type  = gem_type,
        search    = search,
        min_score = min_hidden_score,
        offset    = offset,
        limit     = limit,
    )


@router.get("/semantic/search")
async def semantic_search(q: str = Query(..., min_length=2)):
    q_lower = q.lower()
    matches = [
        g for g in SEED_GEMS
        if q_lower in g["name"].lower()
        or q_lower in g["state"].lower()
        or q_lower in g["region"].lower()
        or q_lower in g["story"].lower()
        or any(q_lower in t.lower() for t in g["tags"])
    ]
    return {"results": matches[:8], "query": q, "source": "keyword"}


@router.get("/{gem_id}")
async def get_gem(gem_id: str, db: AsyncSession = Depends(get_db)):
    for g in SEED_GEMS:
        if g["id"] == gem_id:
            return g
    try:
        result = await db.execute(select(HiddenGem).where(HiddenGem.id == gem_id))
        gem    = result.scalar_one_or_none()
        if gem:
            return _gem_to_dict(gem)
    except Exception:
        pass
    from fastapi import HTTPException
    raise HTTPException(404, "Gem not found")


def _gem_to_dict(g: HiddenGem) -> dict:
    return {
        "id": g.id, "name": g.name, "state": g.state, "region": g.region,
        "type": g.type, "story": g.story, "best_time": g.best_time,
        "crowd_level": g.crowd_level, "photo_spot": g.photo_spot,
        "local_food": g.local_food, "hidden_score": g.hidden_score,
        "tags": g.tags or [], "lat": g.lat, "lng": g.lng,
    }


def _filter_seeds(
    seeds: list,
    state: Optional[str],
    region: Optional[str],
    gem_type: Optional[str],
    search: Optional[str],
    min_score: int,
    offset: int,
    limit: int,
) -> list:
    result = [g for g in seeds if g["hidden_score"] >= min_score]

    # State filter — strict: "Andhra Pradesh" must be in state field
    if state and state not in ("All States", ""):
        result = [g for g in result if state.lower() in g["state"].lower()]

    # Region filter — strict: "Kadapa District" must be in region field
    # This prevents Nellore gems showing when Kadapa is selected
    if region and region not in ("All Districts", ""):
        result = [g for g in result if region.lower() in g.get("region", "").lower()]

    if gem_type and gem_type not in ("All", ""):
        result = [g for g in result if gem_type.lower() in g["type"].lower()]

    if search:
        s = search.lower()
        result = [
            g for g in result
            if s in g["name"].lower()
            or s in g["state"].lower()
            or s in g.get("region", "").lower()
            or s in g["story"].lower()
            or any(s in t.lower() for t in g["tags"])
        ]

    return result[offset: offset + limit]
